#!/usr/bin/env bash
# Install Pennbridge Order Desk on a fresh Ubuntu server (22.04/24.04), from this checkout. Safe to re-run: never overwrites .env or secrets.
#   sudo scripts/install.sh --domain orders.example.co.uk [--acme-email you@example.co.uk] [--tls auto|internal|custom] [--gemini-key-file FILE]
# Test/dev flags: --no-docker-install --no-start --http-port N --https-port N --bind ADDR   (env: PB_PROJECT, PB_ENV_FILE, PB_DATA_DIR)
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"
domain=""; tls=auto; gemini=""; install_docker=1; start=1; http_port=80; https_port=443; bind=0.0.0.0
while [[ $# -gt 0 ]]; do case "$1" in
  --domain) domain="$2"; shift 2;; --tls) tls="$2"; shift 2;; --gemini-key-file) gemini="$2"; shift 2;;
  --http-port) http_port="$2"; shift 2;; --https-port) https_port="$2"; shift 2;; --bind) bind="$2"; shift 2;;
  --no-docker-install) install_docker=0; shift;; --no-start) start=0; shift;; --acme-email) shift 2;;
  -h|--help) sed -n 2,5p "$0"; exit 0;; *) pb_die "unknown option $1";; esac; done
[[ -n "$domain" ]] || pb_die "--domain is required (the host name staff will type, e.g. orders.example.co.uk)"
[[ "$tls" =~ ^(auto|internal|custom)$ ]] || pb_die "--tls must be auto, internal or custom"
[[ "$domain" =~ ^[A-Za-z0-9.-]+$ ]] || pb_die "--domain must be a plain host name"

if ! docker compose version >/dev/null 2>&1; then
  [[ $install_docker -eq 1 ]] || pb_die "docker compose is not installed"
  [[ $EUID -eq 0 ]] || pb_die "run with sudo so Docker can be installed"
  echo "Installing Docker from the Ubuntu repositories..."
  apt-get update -y && apt-get install -y docker.io docker-compose-v2 curl openssl
  systemctl enable --now docker
fi
command -v openssl >/dev/null || pb_die "openssl is required"

data="${PB_DATA_DIR:-$PB_ROOT}"   # where backups/, certs/, secrets/ and runtime/mailbox live (default: this checkout)
backup_dir="$data/backups"; cert_dir="$data/certs"; secrets_dir="$data/secrets"; mailbox_dir="$data/runtime/mailbox"
umask 077
mkdir -p "$backup_dir" "$cert_dir" "$secrets_dir" "$data/runtime"
if [[ -f "$PB_ENV_FILE" ]]; then
  echo "Keeping existing $PB_ENV_FILE (delete it to regenerate; the database password would then no longer match the data volume)."
else
  cat > "$PB_ENV_FILE" <<ENV
# Generated by scripts/install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Contains secrets: keep mode 600, never commit, back it up privately.
PB_DOMAIN=$domain
PB_TLS_MODE=$tls
PB_BIND=$bind
PB_HTTP_PORT=$http_port
PB_HTTPS_PORT=$https_port
POSTGRES_PASSWORD=$(openssl rand -hex 24)
PB_BACKUP_DIR=$backup_dir
PB_CERT_DIR=$cert_dir
PB_SECRETS_DIR=$secrets_dir
PB_MAILBOX_DIR=$mailbox_dir
BACKUP_RETAIN_DAYS=14
BACKUP_HOUR_UTC=02
BACKUP_MINUTE_UTC=30
# Live AI (Gemini). Off by default: orders then go to manual entry. See docs/OPERATIONS.md.
LIVE_AI_ENABLED=false
AI_PROVIDER=gemini
EXTRACTION_MODEL=gemini-3.5-flash-lite
AI_INPUT_USD_PER_MILLION=0.30
AI_OUTPUT_USD_PER_MILLION=2.50
AI_PRICING_VERSION=gemini-3.5-flash-lite-2026-10-28
# Monthly model spend cap and per-order cap, in USD.
AI_RUN_BUDGET_USD=5.00
AI_ORDER_BUDGET_USD=0.25
ENV
  chmod 600 "$PB_ENV_FILE"; echo "Wrote $PB_ENV_FILE"
fi
if [[ -n "$gemini" ]]; then
  [[ -s "$gemini" ]] || pb_die "Gemini key file $gemini is empty or missing"
  install -m 600 "$gemini" "$secrets_dir/gemini_key"
  sed -i.bak 's/^LIVE_AI_ENABLED=.*/LIVE_AI_ENABLED=true/' "$PB_ENV_FILE" && rm -f "$PB_ENV_FILE.bak"
fi
if [[ "$tls" == custom && ! -f "$cert_dir/fullchain.pem" ]]; then echo "NOTE: copy your certificate to $cert_dir/fullchain.pem and key to $cert_dir/privkey.pem before starting."; fi
[[ $start -eq 1 ]] || { echo "Prepared. Start with: scripts/pbctl.sh up -d --build"; exit 0; }

pb_compose up -d --build
echo "Waiting for the desk to become ready..."
for _ in $(seq 1 90); do pb_ready_json >/dev/null 2>&1 && break; sleep 3; done
pb_ready_json || pb_die "the desk did not become ready; see: scripts/pbctl.sh logs --tail 100 app worker db"
cat <<DONE

Installed. Next steps:
  1. Point DNS for $domain at this server and open ports 80 and 443 (certificate issue needs both).
  2. Create the first administrator:   scripts/pbctl.sh exec app npx tsx scripts/create_admin.ts
  3. Load your catalogue and customers (Administration > Import), then configure the mailbox and (optionally) Gemini.
  Full guide: docs/OPERATIONS.md      Health check: scripts/status.sh
DONE
